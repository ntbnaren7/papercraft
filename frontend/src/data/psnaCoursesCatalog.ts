export function findCourseByCode(code?: string | null): CoursePreset | undefined {
  if (!code) return undefined;
  const norm = code.toUpperCase().trim();
  return PSNA_COURSE_PRESETS.find((c) => c.code.toUpperCase() === norm);
}

export function findCourseByName(name?: string | null): CoursePreset | undefined {
  if (!name) return undefined;
  const norm = name.toLowerCase().trim();
  return PSNA_COURSE_PRESETS.find((c) => c.name.toLowerCase().includes(norm));
}
